class ResourceStringValueParser:
    #------------------------------------------------------------#
    @staticmethod
    def parse(value: str):
        #------------------------------------------------------------#
        value = value.strip()
        #------------------------------------------------------------#
        if not value:
            return ""
        #============================================================#
        # strings
        if len(value) >= 2:
            #------------------------------------------------------------#
            if value[0] == "'" and value[-1] == "'":
                return value[1:-1]
            #------------------------------------------------------------#
            if value[0] == '"' and value[-1] == '"':
                return value[1:-1]
        #============================================================#
        # bool
        lowered = value.lower()
        #------------------------------------------------------------#
        if lowered in ("true", "t"):
            return True
        #------------------------------------------------------------#
        if lowered in ("false", "f"):
            return False
        #============================================================#
        # None
        if lowered in ("none", "null"):
            return None
        #============================================================#
        # numbers
        try:
            #------------------------------------------------------------#
            if "." in value:
                return float(value)
            #------------------------------------------------------------#
            return int(value)
        #============================================================#
        except ValueError:
            pass
        #============================================================#
        # string sem aspas
        return value

    